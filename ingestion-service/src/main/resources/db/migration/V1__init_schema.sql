-- V1: initial schema. Mirrors MarketEventEntity and SentimentAlertEntity
-- (Spring Boot's snake_case naming; Instant -> timestamptz) so that
-- spring.jpa.hibernate.ddl-auto=validate passes.

CREATE TABLE market_events (
    event_id     VARCHAR(255)     NOT NULL PRIMARY KEY,
    asset_symbol VARCHAR(255)     NOT NULL,
    type         VARCHAR(255)     NOT NULL,
    raw_text     TEXT,
    price        DOUBLE PRECISION,
    "timestamp"  TIMESTAMPTZ      NOT NULL,
    created_at   TIMESTAMPTZ      NOT NULL
);

CREATE INDEX idx_market_events_asset_symbol ON market_events (asset_symbol);

CREATE TABLE sentiment_alerts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR(255)     NOT NULL,
    asset_symbol    VARCHAR(255)     NOT NULL,
    sentiment_score DOUBLE PRECISION NOT NULL,
    primary_label   VARCHAR(255)     NOT NULL,
    is_anomaly      BOOLEAN          NOT NULL,
    processed_at    TIMESTAMPTZ      NOT NULL,
    created_at      TIMESTAMPTZ      NOT NULL
);

CREATE INDEX idx_sentiment_alerts_event_id     ON sentiment_alerts (event_id);
CREATE INDEX idx_sentiment_alerts_asset_symbol ON sentiment_alerts (asset_symbol);
